"""Synthetic European chain -> cleaning -> forwards -> smiles -> surface -> arbitrage diagnostics.

Everything here is SYNTHETIC (generated by :func:`optpricer.market.synthetic_european_chain`).
An optional delayed market snapshot, if one exists in data/snapshots, is summarised
separately and labelled as American-style with descriptive BSM IVs only.
"""

from __future__ import annotations

import datetime as dt
import math
from pathlib import Path

import numpy as np
import pandas as pd

from ..market import CleaningPolicy, SSVIParams, clean_chain, cleaning_summary, save_snapshot, synthetic_european_chain
from ..paths import data_dir
from ..surface import TotalVarianceSurface, arbitrage_diagnostics, build_smiles, implied_forwards, risk_neutral_density
from .common import PALETTE, SEQ_BLUE, plt, save_fig, save_table

LABEL = "SYNTHETIC European chain (SSVI generator, seeded) - not market data"


def surface_experiments(cfg: dict) -> dict:
    syn = cfg["synthetic"]
    p = SSVIParams(rho=syn["ssvi"]["rho"], eta=syn["ssvi"]["eta"], gamma=syn["ssvi"]["gamma"],
                   atm_vols=tuple(syn["ssvi"]["atm_vols"]))
    vt = dt.datetime.fromisoformat(syn["valuation_time"])
    chain, truth = synthetic_european_chain(syn["S"], syn["r"], syn["q"], tuple(syn["expiry_days"]), p, syn["seed"], vt)
    save_snapshot(chain, {"label": "SYNTHETIC", "source": "optpricer.market.synthetic_european_chain",
                          "seed": syn["seed"], "valuation_time": vt.isoformat(), "exercise_style": "european",
                          "currency": "synthetic units", "truth": truth,
                          "note": "fictional timestamps; defects injected deliberately (column injected_defect)"},
                  data_dir("synthetic"), "synthetic_european_chain")
    cl_cfg = cfg["cleaning"]
    pol = CleaningPolicy(max_rel_spread=cl_cfg["max_rel_spread"], min_abs_spread=cl_cfg["min_abs_spread"],
                         min_days=cl_cfg["min_days"], stale_seconds=cl_cfg["stale_seconds"],
                         zero_bid=cl_cfg["zero_bid"], r=syn["r"], q=syn["q"])
    cl = clean_chain(chain, pol)
    save_table(cl, "chain_cleaned_with_reasons")
    summ = cleaning_summary(cl)
    detected = cl[cl.injected_defect != ""]
    summ_inj = pd.DataFrame([dict(injected=d, n=int((detected.injected_defect == d).sum()),
                                  caught=int(((detected.injected_defect == d) & ~detected.accepted).sum()))
                             for d in sorted(detected.injected_defect.unique())])
    save_table(summ, "quote_cleaning_summary")
    save_table(summ_inj, "quote_cleaning_injected_defects")

    fig, ax = plt.subplots(figsize=(7.5, 4.0))
    s = summ[~summ.reason.str.startswith("TOTAL")]
    ax.barh(s.reason, s["count"], color=PALETTE[0], height=0.6)
    for y, v in enumerate(s["count"]):
        ax.text(v + 0.1, y, str(v), va="center", fontsize=8)
    tot_rej = int(summ.loc[summ.reason == "TOTAL_REJECTED_ROWS", "count"].iloc[0])
    ax.set_title(f"Quote cleaning: {tot_rej} of {len(cl)} quotes rejected (reasons can overlap)")
    ax.set_xlabel("quotes")
    save_fig(fig, "10_quote_cleaning_summary",
             f"{LABEL}. Rules: crossed/missing/negative, zero bid (policy=reject), spread > 50% of mid and > 0.05, "
             "stale > 900 s, expiry < 7 days, bound violation. All 12 injected defects are flagged; other rejections "
             "are genuine wide-spread / zero-bid deep-OTM quotes.")

    fw = implied_forwards(cl, n_near=cfg["forward_pairs"])
    tr = pd.DataFrame(truth["expiries"])
    fw = fw.merge(tr.rename(columns={"F": "F_true", "DF": "DF_true"})[["expiry", "F_true", "DF_true"]], on="expiry")
    fw["F_error"] = fw["F"] - fw["F_true"]
    fw["DF_error"] = fw["DF"] - fw["DF_true"]
    save_table(fw, "implied_forwards")

    sm = build_smiles(cl, fw)
    sm["iv_error_vs_true"] = sm["iv"] - sm["true_iv"]
    save_table(sm, "smiles")
    fig, ax = plt.subplots(figsize=(7.8, 4.6))
    for i, (exp, g) in enumerate(sm.groupby("expiry", sort=True)):
        g = g.sort_values("k")
        ax.plot(g["k"], g["iv"], marker="o", ms=3, lw=1.4, color=PALETTE[i % 8],
                label=f"{exp} (T={g['T'].iloc[0]:.2f})")
        ax.fill_between(g["k"], g["iv_bid"], g["iv_ask"], color=PALETTE[i % 8], alpha=0.12, lw=0)
    ax.set_xlabel("log-forward moneyness k = ln(K/F)")
    ax.set_ylabel("implied volatility (mid; band = bid-ask IV)")
    ax.set_title("Smiles across expiries (OTM quotes, parity-implied F and DF)")
    ax.legend(fontsize=7.5)
    save_fig(fig, "11_smiles_across_expiries",
             f"{LABEL}. Valuation time {vt:%Y-%m-%d %H:%M} (fictional). True smile: SSVI rho={p.rho}, eta={p.eta}, "
             "gamma=0.5. European exercise. Forward and DF estimated by WLS parity on matched mids.")

    surf = TotalVarianceSurface(sm)
    kgrid = np.linspace(-0.4, 0.3, 57)
    Tgrid = np.linspace(surf.T[0], surf.T[-1], 40)
    IV = np.array([surf.iv(kgrid, T) for T in Tgrid])
    grid_df = pd.DataFrame([dict(T=T, k=k, iv=IV[i, j]) for i, T in enumerate(Tgrid) for j, k in enumerate(kgrid)])
    save_table(grid_df, "surface_grid")
    fig = plt.figure(figsize=(11.5, 4.6))
    ax1 = fig.add_subplot(1, 2, 1, projection="3d")
    KK, TT = np.meshgrid(kgrid, Tgrid)
    ax1.plot_surface(KK, TT, IV, cmap=SEQ_BLUE, linewidth=0, antialiased=True, alpha=0.95)
    ax1.set_xlabel("k = ln(K/F)")
    ax1.set_ylabel("T (years)")
    ax1.set_zlabel("implied vol")
    ax1.set_title("Interpolated surface (linear total variance)")
    ax2 = fig.add_subplot(1, 2, 2)
    cs = ax2.contourf(KK, TT, IV, levels=14, cmap=SEQ_BLUE)
    fig.colorbar(cs, ax=ax2, label="implied vol")
    ax2.scatter(sm["k"], sm["T"], s=6, color="#0b0b0b", alpha=0.6, label="quoted points")
    ax2.set_xlabel("k = ln(K/F)")
    ax2.set_ylabel("T (years)")
    ax2.set_title("Same surface, top view, with quote locations")
    ax2.legend(fontsize=8, loc="upper left")
    save_fig(fig, "12_vol_surface",
             f"{LABEL}. w = sigma^2 T interpolated linearly in k per slice (flat beyond quotes) and linearly in T. "
             "Interpolation is NOT a guarantee of no-arbitrage; extrapolated corners are crude.")

    viol, asumm = arbitrage_diagnostics(cl, fw, sm)
    save_table(viol, "arbitrage_violations")
    save_table(asumm, "arbitrage_summary")
    # control experiment: same chain at true prices + injected violations, to show detection
    clean_true, _ = synthetic_european_chain(syn["S"], syn["r"], syn["q"], tuple(syn["expiry_days"]), p, syn["seed"],
                                             vt, inject_defects=False)
    clean_true["bid"] = clean_true["ask"] = clean_true["mid"] = clean_true["true_price"]
    clean_true["accepted"] = True
    fw_true = tr.assign(implied_rate=syn["r"], implied_yield=syn["q"])
    sm_true = build_smiles(clean_true, fw_true)
    _, s_true = arbitrage_diagnostics(clean_true, fw_true, sm_true, tol=1e-9)
    inj = clean_true.copy()
    e0 = tr["expiry"].iloc[1]
    i_conv = inj[(inj.expiry == e0) & (inj.kind == "call") & (inj.strike == 100.0)].index[0]
    inj.loc[i_conv, ["mid", "bid", "ask"]] += 0.4
    i_mono = inj[(inj.expiry == e0) & (inj.kind == "call") & (inj.strike == 110.0)].index[0]
    inj.loc[i_mono, ["mid", "bid", "ask"]] = inj.loc[inj[(inj.expiry == e0) & (inj.kind == "call") &
                                                          (inj.strike == 109.0)].index[0], "mid"] + 0.2
    sm_inj = build_smiles(inj, fw_true)
    sm_inj.loc[sm_inj["T"] == sorted(sm_inj["T"].unique())[3], "w"] *= 0.5  # injected calendar defect
    _, s_inj = arbitrage_diagnostics(inj, fw_true, sm_inj, tol=1e-9)
    ctrl = pd.concat([s_true.assign(dataset="true SSVI prices (no noise)"),
                      asumm.assign(dataset="noisy synthetic quotes (cleaned)"),
                      s_inj.assign(dataset="true prices + injected violations")])
    save_table(ctrl, "arbitrage_diagnostic_report")

    fig, ax = plt.subplots(figsize=(9, 4.2))
    checks = list(asumm.check)
    x = np.arange(len(checks))
    wdt = 0.26
    for i, (name, d) in enumerate(ctrl.groupby("dataset", sort=False)):
        d = d.set_index("check").loc[checks]
        ax.bar(x + (i - 1) * wdt, d["violations_mid"], width=wdt - 0.02, color=PALETTE[i], label=f"{name}: mid")
        ax.bar(x + (i - 1) * wdt, d["violations_executable"], width=wdt - 0.02, color="none", edgecolor="#0b0b0b",
               hatch="///", lw=0.6)
        for xx, v in zip(x + (i - 1) * wdt, d["violations_mid"]):
            ax.text(xx, v + 0.2, str(int(v)), ha="center", fontsize=7.5)
    ax.set_xticks(x, checks)
    ax.set_ylabel("violations on the finite quote grid")
    ax.set_title("Static-arbitrage diagnostics (hatched = executable at bid/ask)")
    ax.legend(fontsize=7.5)
    save_fig(fig, "13_arbitrage_diagnostics",
             f"{LABEL}. Checks on a finite strike grid only; zero violations does not prove a continuous surface is "
             "arbitrage-free. Calendar check compares total variance at equal k (forward-normalised). Calendar "
             "'executable' is an IV-space bid/ask proxy, not a priced trade.")

    # risk-neutral density for one expiry (true vs noisy)
    e3 = tr.iloc[3]
    dens_rows = []
    for lab, src in (("true prices", clean_true), ("noisy cleaned mids", cl)):
        g = src[(src.expiry == e3["expiry"]) & (src.kind == "call")]
        if "accepted" in g:
            g = g[g.accepted]
        d = risk_neutral_density(g.strike, g.mid, e3["DF"])
        d["dataset"] = lab
        dens_rows.append(d)
    dens = pd.concat(dens_rows)
    save_table(dens, "risk_neutral_density")
    return {"cleaning": summ, "forwards": fw, "smiles": sm, "arbitrage": ctrl, "violations": viol,
            "n_quotes": len(cl), "n_accepted": int(cl.accepted.sum())}


def market_snapshot_summary() -> pd.DataFrame | None:
    """Summarise any saved delayed market snapshot (American-style; descriptive IVs only)."""
    snaps = sorted(Path(data_dir("snapshots")).glob("*.csv"))
    if not snaps:
        return None
    from ..implied_vol import implied_vol
    from ..market import load_snapshot

    df, meta = load_snapshot(snaps[-1])
    r = float(meta.get("rate_assumption_for_descriptive_iv", 0.04))
    cl = clean_chain(df, CleaningPolicy(r=r, q=0.0))
    csumm = cleaning_summary(cl)
    csumm["snapshot"] = snaps[-1].name
    csumm["retrieved_utc"] = meta.get("retrieved_utc")
    csumm["share_zero_bid"] = float((df["bid"] == 0).mean())
    save_table(csumm, "market_snapshot_cleaning_summary")
    ok = cl[cl.accepted].copy()
    if len(ok) < 20:
        # Not enough usable two-sided quotes (e.g. snapshot taken outside trading hours): report, do not plot.
        save_table(ok, "market_snapshot_descriptive_iv")
        return ok
    S = float(ok["underlying_price"].iloc[0]) if len(ok) else math.nan
    ok = ok[((ok.kind == "call") & (ok.strike >= S)) | ((ok.kind == "put") & (ok.strike < S))]
    ivs = [implied_vol(float(row.mid), float(row.underlying_price), float(row.strike), float(row.T),  # type: ignore[arg-type]
                       r, 0.0, str(row.kind), "american", approximate_american=True) for row in ok.itertuples()]
    ok["iv_descriptive"] = [x.iv for x in ivs]
    ok["iv_label"] = [x.label for x in ivs]
    ok["k_spot"] = np.log(ok.strike / S)
    save_table(ok, "market_snapshot_descriptive_iv")
    fig, ax = plt.subplots(figsize=(7.8, 4.5))
    for i, (exp, g) in enumerate(ok.groupby("expiry", sort=True)):
        g = g.sort_values("k_spot")
        ax.plot(g["k_spot"], g["iv_descriptive"], marker="o", ms=2.5, lw=1.2, color=PALETTE[i % 8], label=str(exp))
    ax.set_xlabel("ln(K/S) (spot moneyness; no forward inferred from American quotes)")
    ax.set_ylabel("BSM-European IV (descriptive approximation)")
    ax.set_title(f"{meta.get('source', 'market snapshot')}: DESCRIPTIVE smiles")
    ax.legend(fontsize=7)
    save_fig(fig, "11b_market_snapshot_descriptive_smiles",
             f"MARKET_DELAYED, AMERICAN-style quotes, retrieved {meta.get('retrieved_utc', '?')} UTC. European BSM IV "
             f"with assumed r={r}, q=0: a descriptive approximation that ignores early exercise and "
             "discrete dividends. "
             "Not used for arbitrage certification.")
    return ok
